package greedy;

public class BoundaryCheck {
    public static void main(String[] args) {
        System.out.println("Int Max: " +
                Integer.MAX_VALUE);
        System.out.println("Int Min: " +
                Integer.MIN_VALUE);
        System.out.println("Int Max + 1: " +
                (Integer.MAX_VALUE + 1));
        System.out.println("Int Min - 1: " +
                (Integer.MIN_VALUE - 1));
        System.out.println(~-5000);
    }
}
